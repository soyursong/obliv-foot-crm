-- ── 2) DRIFT-GUARD (apply-직전 재-freeze) — 각 frozen PK가 지문 유지 재확인 ──
DO $$
DECLARE fcnt int; ecnt int; drift int;
BEGIN
  SELECT count(*) INTO fcnt FROM _freeze;
  IF fcnt <> 582 THEN RAISE EXCEPTION 'FREEZE COUNT % != 582 — ABORT', fcnt; END IF;

  SELECT count(*) INTO ecnt FROM _freeze f JOIN public.notification_logs nl ON nl.id=f.id;
  IF ecnt <> 582 THEN RAISE EXCEPTION 'frozen PK 존재수 % != 582(행 삭제/유실) — ABORT', ecnt; END IF;

  SELECT count(*) INTO drift
    FROM _freeze f JOIN public.notification_logs nl ON nl.id=f.id
   WHERE NOT (nl.recipient_phone LIKE 'DUMMY-%' AND nl.customer_id IS NULL AND nl.status='sent');
  IF drift <> 0 THEN
    RAISE EXCEPTION 'DRIFT-ABORT: %개 frozen 행이 지문 이탈(status!=sent 등) — ABORT', drift;
  END IF;
END $$;

