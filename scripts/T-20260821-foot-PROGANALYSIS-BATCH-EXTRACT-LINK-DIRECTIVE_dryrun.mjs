#!/usr/bin/env node
/**
 * T-20260821-foot-PROGANALYSIS-BATCH-EXTRACT-LINK-DIRECTIVE (Phase-2 §4/§5)
 * no-persistence dry-run evidence — supervisor DB-GATE-HOLD (MSG-20260822-013137-93h7 / -013222-gagk)
 *
 * 표준: agents/docs/migration_dryrun_no_persistence_standard.md (dryrun_lib.mjs 3요소 구조)
 *  ① stripTxnControl(top-level BEGIN/COMMIT 제거) ② plpgsql exception-handler(무영속) ③ assertAbsent post-probe.
 *
 * RUN A: forward 만 → self-verify DO 통과(생성 실증) + sentinel 롤백 + 11개 absent 프로브(무영속 실증).
 * RUN B: forward + rollback 연결 → 11개 absent 프로브(롤백이 forward 를 clean 하게 역전 실증).
 *
 * AC-0: 이 러너는 apply 가 아니다. DDL 은 subtransaction 에서 sentinel RAISE 로 강제 롤백된다(prod 영속 0).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  runDryrun, buildHarness, detectNonTxnDdl,
  regclassAbsent, columnAbsent, policyAbsent, triggerAbsent, procAbsent,
} from './dryrun_lib.mjs';

const __dir = dirname(fileURLToPath(import.meta.url));
const MIG = join(__dir, '..', 'supabase', 'migrations', '20260822010000_foot_progress_analysis_slips_schema.sql');
const RBK = join(__dir, '..', 'supabase', 'migrations', '20260822010000_foot_progress_analysis_slips_schema.rollback.sql');

// ── INV-3 post-probe: 이 마이그가 신설하는 전 오브젝트의 prod 부재 실측(무영속 증적) ──
const PROBES = [
  regclassAbsent('public.progress_analysis_slips'),
  regclassAbsent('public.progress_analysis_slips_audit_log'),
  columnAbsent('progress_result_images', 'slip_id'),
  columnAbsent('progress_result_images', 'deleted_at'),
  columnAbsent('progress_result_images', 'deleted_by'),
  columnAbsent('progress_result_images', 'delete_reason'),
  columnAbsent('progress_result_images', 'is_deleted'),
  policyAbsent('progress_analysis_slips', 'pas_clinic_gate'),
  policyAbsent('progress_result_images', 'pri_deleted_rows_admin_only'),
  triggerAbsent('trg_progress_analysis_slips_audit', 'progress_analysis_slips'),
  triggerAbsent('trg_progress_result_images_harddelete_guard', 'progress_result_images'),
  procAbsent('progress_analysis_slips_audit'),
  procAbsent('progress_result_images_harddelete_guard'),
];

const fwd = readFileSync(MIG, 'utf8');
const rbk = readFileSync(RBK, 'utf8');

// ── 무영속 불가 DDL 검출(표준 §5): 있으면 dry-run 불가 → hard-fail ──
const nonTxn = [...detectNonTxnDdl(fwd), ...detectNonTxnDdl(rbk)];
if (nonTxn.length) {
  console.error('NON_TXN_DDL_CANNOT_DRYRUN:', nonTxn);
  process.exit(2);
}
console.log('§5 non-txn DDL 검출 = 0 (전 DDL 트랜잭션 봉투 dry-run 가능)\n');

// ── .dryrun.sql 아티팩트: RUN A harness(strip+sentinel+exception-handler) 영속 ──
const { harness, removed } = buildHarness(fwd);
const artifactPath = join(__dir, '..', 'supabase', 'migrations', '20260822010000_foot_progress_analysis_slips_schema.dryrun.sql');
writeFileSync(artifactPath,
`-- no-persistence dry-run harness (RUN A: forward) — GENERATED by ${'T-20260821-foot-PROGANALYSIS-BATCH-EXTRACT-LINK-DIRECTIVE_dryrun.mjs'}
-- strip 된 top-level txn 제어문(INV-5 비침묵): ${JSON.stringify(removed)}
-- sentinel RAISE 로 subtransaction 강제 롤백 → prod 영속 0. 아래는 실제 전송된 harness SQL.
${harness}
`);
console.log(`✔ .dryrun.sql artifact 기록: ${artifactPath}`);
console.log(`  strip 된 top-level txn 문(INV-5): ${JSON.stringify(removed)}\n`);

// ── RUN A: forward only ──
console.log('════════ RUN A: forward dry-run (self-verify DO + 무영속) ════════');
const a = await runDryrun({ upPath: MIG, assertAbsent: PROBES,
  passNote: 'forward: slips 후보B + audit_log + images additive(deleted_at authority/is_deleted GENERATED/slip_id) 생성 → self-verify DO 통과 → sentinel 롤백',
  exitProcess: false });

// ── RUN B: forward + rollback 연결(round-trip) ──
console.log('\n════════ RUN B: forward+rollback round-trip dry-run (롤백 역전 실증) ════════');
const combinedPath = join(__dir, '..', 'supabase', 'migrations', '_tmp_20260822010000_roundtrip.sql');
writeFileSync(combinedPath, fwd + '\n\n-- ===== ROLLBACK =====\n\n' + rbk);
const b = await runDryrun({ upPath: combinedPath, assertAbsent: PROBES,
  passNote: 'round-trip: forward 적용 후 rollback 으로 전 오브젝트 역전 → 동일 subtransaction 내 clean reverse → sentinel 롤백',
  exitProcess: false });
try { readFileSync(combinedPath) && (await import('node:fs')).unlinkSync(combinedPath); } catch {}

console.log('\n════════ 종합 ════════');
console.log(`RUN A (forward)        : ${a?.pass ? 'PASS' : 'FAIL'}`);
console.log(`RUN B (forward+rollback): ${b?.pass ? 'PASS' : 'FAIL'}`);
const ok = a?.pass && b?.pass;
console.log(ok ? '\n✅ no-persistence dry-run PASS (forward+rollback 무영속 · 11개 오브젝트 prod 부재 실측)'
              : '\n❌ FAIL');
process.exit(ok ? 0 : 1);
